// 根据六爻数组查找卦象
export function findHexagram(lines) {
  const binary = lines.map(line => line.value === 9 || line.value === 7 ? 1 : 0);
  return hexagrams.find(h =>
    h.binary.every((bit, index) => bit === binary[index])
  );
}

// 获取变卦
export function getChangingHexagram(lines) {
  const changingBinary = lines.map(line => {
    if (line.value === 6) return 1; // 老阴变阳
    if (line.value === 9) return 0; // 老阳变阴
    return line.value === 7 ? 1 : 0;
  });

  return hexagrams.find(h =>
    h.binary.every((bit, index) => bit === changingBinary[index])
  );
}
